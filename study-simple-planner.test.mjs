import assert from "node:assert/strict";
import {scheduleCourses,findScheduleCourse} from "./public/study-workspace.js";
import {studyTaskItems,createTaskStudySession,removeStudyScheduleEntry,removeCourseStudyTask,studyCalendarEntries,courseStudyTasks} from "./public/study-plan-core.js";
import {studyTaskIndex,reconcileLinkedTasks,setStudyTaskDone} from "./public/study-task-sync.js";
import {previewWeeklyRule,applyWeeklyRule,refreshWeeklyRules} from "./public/study-batch-core.js";
import {captureCoursePlan,recordCoursePlanChange,coursePlanVersions,restoreCoursePlanVersion} from "./public/study-plan-history.js";
const tasks=[7,8,9,10].map(n=>({id:"t"+n,title:"Week "+n,estimatedHours:2,done:false,note:"Keep",attachments:[]}));
const state={semesters:[{id:"s",name:"Winter",courses:[{id:"c",name:"K&C",categories:[{id:"ha",name:"Hausaufgabe",tasks}]}]}],timer:{sessions:[{id:"actual",taskId:"t7",startAt:1,endAt:3600001,durationMs:3600000}],calendarItems:[]}};
const id="progress-c";
assert.equal(studyTaskItems(state,"2026-11-30","2026-12-06").length,4,"Every progress task is available without degree setup or optional linking");
const before=captureCoursePlan(state,id);
const config={categoryId:"ha",mappingMode:"sequence",startTaskId:"t7",fromWeek:"2026-11-30",untilWeek:"2026-12-27",weekday:3,startTime:"19:00",endTime:"21:00",skipWeeks:[]};
const preview=previewWeeklyRule(state,id,config,"2026-11-28");
assert.deepEqual(preview.rows.map(r=>r.date),["2026-12-02","2026-12-09","2026-12-16","2026-12-23"]);
applyWeeklyRule(state,id,preview.rule,preview.rows,"2026-11-28");
assert.equal(refreshWeeklyRules(state,"2026-11-28"),0);
const course=findScheduleCourse(state,id);
assert.equal(course.planEvents.length,4);
assert.equal(state.degreePlan,undefined,"Scheduling never creates credit modules");
removeStudyScheduleEntry(state,id,"plan-event:"+course.planEvents[0].id+":2026-12-02","2026-12-02");
assert.equal(refreshWeeklyRules(state,"2026-11-28"),0,"Canceled session is not automatically recreated");
assert.equal(studyTaskItems(state,"2026-11-30","2026-12-06").find(t=>t.taskId==="t7").allocations.length,0);
const first=createTaskStudySession(state,id,"t7",{date:"2026-12-01",startTime:"19:00",endTime:"20:00",hours:1});
assert.equal(studyTaskItems(state,"2026-11-30","2026-12-06").find(t=>t.taskId==="t7").remainingHours,1);
assert.equal(tasks.find(t=>t.id==="t7").done,false,"Actual hours never complete content");
setStudyTaskDone(state,"t7",true,id);assert.equal(state.semesters[0].courses[0].categories[0].tasks[0].done,true);
setStudyTaskDone(state,"t7",false,id);
removeCourseStudyTask(state,id,"t7");
assert.equal(studyTaskItems(state,"2026-11-30","2026-12-06").some(t=>t.taskId==="t7"),false);
assert.equal(studyCalendarEntries(state,"2026-11-30","2026-12-06").some(t=>t.taskId==="t7"),false);
assert.equal(state.timer.sessions.length,1);
const snapshot=studyTaskIndex(state);state.semesters[0].courses[0].categories[0].tasks=state.semesters[0].courses[0].categories[0].tasks.filter(t=>t.id!=="t8");
reconcileLinkedTasks(state,snapshot,"2026-12-30");
assert.equal(course.planEvents.some(t=>t.taskId==="t8"),false,"Deleting a task from progress also removes its past planned block");
assert.ok(course.planEventArchive.some(a=>a.event.taskId==="t8"));
recordCoursePlanChange(state,id,before,"Test");
assert.ok(coursePlanVersions(course).length>=2);
const saved=JSON.parse(JSON.stringify(state));
assert.equal(findScheduleCourse(saved,id).planEvents.length,2,"Source course metadata survives storage");
const legacy={semesters:[],degreePlan:{blocks:[],modules:[{courses:[{id:"legacy",name:"Legacy",exams:[],tasks:[{id:"old",title:"Task",done:true,hours:2,note:"Notes"}],planEvents:[{id:"slot",taskId:"old",title:"Task",type:"study",date:"2026-12-01",startTime:"19:00",endTime:"21:00"}]}]}]},timer:{sessions:[],calendarItems:[]}};
reconcileLinkedTasks(legacy);const lc=legacy.degreePlan.modules[0].courses[0];
assert.ok(lc.courseId);assert.equal(lc.tasks.length,0);assert.equal(courseStudyTasks(lc,legacy.semesters)[0].done,true);assert.equal(legacy.semesters[0].courses[0].categories[0].tasks[0].note,"Notes");
assert.equal(studyCalendarEntries(legacy,"2026-12-01","2026-12-01").filter(e=>e.startTime).length,1);
const stable=JSON.stringify(legacy);reconcileLinkedTasks(legacy);assert.equal(JSON.stringify(legacy),stable);
console.log("PASS simple unified planner: all source courses, sequential auto dates, cancel protection, partial allocations, strict completion/deletion sync, history, timer retention and legacy migration");
